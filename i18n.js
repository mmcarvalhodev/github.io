    function applyLang(lang) {
      var t = T[lang] || T['en'];
      // textContent elements
      document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) el.textContent = t[key];
      });
      // innerHTML elements (for bold tags etc.)
      document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
        var key = el.getAttribute('data-i18n-html');
        if (t[key] !== undefined) el.innerHTML = t[key];
      });
      // lang switcher: update trigger label + active state
      var currentEl = document.getElementById('langCurrent');
      if (currentEl) currentEl.textContent = lang.toUpperCase();
      document.querySelectorAll('.lang-opt').forEach(function(opt) {
        opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
      });
      // close dropdown
      var sw = document.getElementById('langSwitcher');
      if (sw) sw.classList.remove('open');
      // SEO meta tags + html lang
      var seo = SEO[lang] || SEO['en'];
      document.title = seo.title;
      document.documentElement.lang = lang;
      var metaDesc = document.querySelector('meta[name="description"]');
      if (metaDesc) metaDesc.setAttribute('content', seo.description);
      var metaKw = document.querySelector('meta[name="keywords"]');
      if (metaKw) metaKw.setAttribute('content', seo.keywords);
      var ogTitle = document.querySelector('meta[property="og:title"]');
      if (ogTitle) ogTitle.setAttribute('content', seo.title);
      var ogDesc = document.querySelector('meta[property="og:description"]');
      if (ogDesc) ogDesc.setAttribute('content', seo.description);
      var twTitle = document.querySelector('meta[name="twitter:title"]');
      if (twTitle) twTitle.setAttribute('content', seo.title);
      var twDesc = document.querySelector('meta[name="twitter:description"]');
      if (twDesc) twDesc.setAttribute('content', seo.description);
      // canonical per language
      var canonical = document.querySelector('link[rel="canonical"]');
      if (canonical) canonical.setAttribute('href', 'https://nodus-ai.app/?lang=' + lang);
      // persist
      try { localStorage.setItem('nodus_lang', lang); } catch(e) {}
    }

    function detectLang() {
      if (window._forcedLang && T[window._forcedLang]) return window._forcedLang;
      try {
        var urlParam = new URLSearchParams(window.location.search).get('lang');
        if (urlParam && T[urlParam]) return urlParam;
      } catch(e) {}
      try {
        var saved = localStorage.getItem('nodus_lang');
        if (saved && T[saved]) return saved;
      } catch(e) {}
      var nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
      if (nav.startsWith('pt')) return 'pt';
      if (nav.startsWith('es')) return 'es';
      if (nav.startsWith('fr')) return 'fr';
      if (nav.startsWith('de')) return 'de';
      if (nav.startsWith('ja')) return 'ja';
      if (nav.startsWith('it')) return 'it';
      if (nav.startsWith('zh')) return 'zh';
      if (nav.startsWith('ko')) return 'ko';
      if (nav.startsWith('hi')) return 'hi';
      return 'en';
    }

    /* Expose T and detectLang globally so other scripts can use them */
    window.T = T;
    window.detectLang = detectLang;

    document.addEventListener('DOMContentLoaded', function() {
      var lang = detectLang();
      applyLang(lang);
      // Dropdown toggle
      var trigger = document.getElementById('langTrigger');
      var switcher = document.getElementById('langSwitcher');
      if (trigger && switcher) {
        trigger.addEventListener('click', function(e) {
          e.stopPropagation();
          var isOpen = switcher.classList.toggle('open');
          trigger.setAttribute('aria-expanded', isOpen);
        });
        document.addEventListener('click', function() {
          switcher.classList.remove('open');
          trigger.setAttribute('aria-expanded', 'false');
        });
      }
      // Hamburger menu toggle
      var hamburger = document.getElementById('navHamburger');
      var navLinks = document.querySelector('.nav-links');
      if (hamburger && navLinks) {
        hamburger.addEventListener('click', function(e) {
          e.stopPropagation();
          hamburger.classList.toggle('open');
          navLinks.classList.toggle('mobile-open');
        });
        document.addEventListener('click', function(e) {
          if (!hamburger.contains(e.target) && !navLinks.contains(e.target)) {
            hamburger.classList.remove('open');
            navLinks.classList.remove('mobile-open');
          }
        });
        navLinks.querySelectorAll('a').forEach(function(a) {
          a.addEventListener('click', function() {
            hamburger.classList.remove('open');
            navLinks.classList.remove('mobile-open');
          });
        });
      }

      // Lang option clicks
      document.querySelectorAll('.lang-opt').forEach(function(opt) {
        opt.addEventListener('click', function(e) {
          e.stopPropagation();
          var selectedLang = opt.getAttribute('data-lang');
          applyLang(selectedLang);
          try { localStorage.setItem('nodus_lang', selectedLang); } catch(e2) {}
          try {
            var url = new URL(window.location.href);
            url.searchParams.set('lang', selectedLang);
            history.replaceState(null, '', url.toString());
          } catch(e3) {}
        });
      });
    });
